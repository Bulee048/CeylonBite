// CeylonBite — maintenance script.
// Removes the audit/verification test accounts created by scripts/live-audit.js
// (and their cascaded Orders / OrderItems / Favorites), then recomputes the
// CEYLON20 promo usage counter from the orders that remain.
//
// Safe by design: it only touches accounts whose Email matches the known
// audit patterns below. It never deletes real customers or menu data.
//
// Run from the backend/ directory:  node scripts/cleanup-test-data.js
const mssql = require('mssql');

const DB_CFG = {
  user: 'CeylonBiteAppUser',
  password: 'CeylonBiteAppSecurePass2026!',
  server: '127.0.0.1',
  port: 1433,
  database: 'CeylonBiteDB',
  options: { encrypt: false, trustServerCertificate: true },
  pool: { max: 4, min: 1 },
};

// Accounts generated by the live audit run.
const AUDIT_EMAIL_PATTERNS = [
  "livecust%@ceylonbite.lk",
  "liveadmin%@ceylonbite.lk",
  "webuitest%@ceylonbite.lk",
  "qafix%@ceylonbite.lk",
  "qaui%@ceylonbite.lk",
];

(async () => {
  const pool = await mssql.connect(DB_CFG);

  const where = AUDIT_EMAIL_PATTERNS.map((p) => `Email LIKE '${p}'`).join(' OR ');
  const preview = (
    await pool.request().query(
      `SELECT UserID, Email, Role, CreatedAt FROM Users WHERE ${where} ORDER BY UserID`
    )
  ).recordset;

  console.log(`Found ${preview.length} audit account(s):`);
  preview.forEach((u) => console.log(`  #${u.UserID}  ${u.Email}  (${u.Role})`));

  if (preview.length > 0) {
    const ids = preview.map((u) => u.UserID);
    const delReq = pool.request();
    ids.forEach((id, i) => delReq.input(`id${i}`, id));
    const delRes = await delReq.query(
      `DELETE FROM Users WHERE UserID IN (${ids.map((_, i) => `@id${i}`).join(', ')})`
    );
    console.log(
      `Deleted ${delRes.rowsAffected[0]} audit user(s) — their orders, order items and favorites cascaded.`
    );
  }

  // Recompute the CEYLON20 usage counter from the orders that actually remain.
  const used = (
    await pool.request().query(`SELECT COUNT(*) AS c FROM Orders WHERE PromoCode = 'CEYLON20'`)
  ).recordset[0].c;
  await pool.request().query(`UPDATE PromoCodes SET UsedCount = ${used} WHERE Code = 'CEYLON20'`);
  console.log(`CEYLON20 UsedCount recomputed -> ${used}`);

  const counts = async (table) =>
    (await pool.request().query(`SELECT COUNT(*) AS c FROM ${table}`)).recordset[0].c;

  console.log(
    `Remaining rows -> Users: ${await counts('Users')}, Orders: ${await counts(
      'Orders'
    )}, OrderItems: ${await counts('OrderItems')}, Favorites: ${await counts(
      'Favorites'
    )}, Foods: ${await counts('Foods')}`
  );

  await pool.close();
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
